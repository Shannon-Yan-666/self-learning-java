package com.yanxiao.demo02_comment;


/**
 * 文档注释：
 *      快捷方式：/** + 回车
 *      作用：对类和方法进行解释说明
 *      注释的测试类
 */

public class demo {

    /**
     * 程序的启动入口方法：main方法
     * @param args
     */
    public static void main(String[] args) {
        // 单行注释：打印 （对当前代码进行解释说明）
        System.out.println("Film");
        System.out.println("Film"); //单行注释：打印

        /*
            多行注释：/* + 回车
            多行注释：/* + 回车
         */
        System.out.println("Film");

    }

}
