package com.yanxiao.demo03_iteral;


/**
 * 目标：掌握现实生活中的数据在程序中的书写形式（字面量）
 * 字面量：
 *      整数--->直接书写
 *      小数--->直接书写
 *      文本--->双引号包裹
 *      字符--->单引号包裹
 *      真假--->True False
 *      空值--->null
 *
 */
public class demo {

    public static void main(String[] args) {
        // 整数
        System.out.println(18);
        // 小数
        System.out.println(88.5);
        // 文本
        System.out.println("广东深圳");
        // 字符
        System.out.println('女');
        // 真
        System.out.println(true);
        // 假
        System.out.println(false);
    }
}

