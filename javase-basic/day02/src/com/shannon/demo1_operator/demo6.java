package com.yanxiao.demo1_operator;
/**
 * 目标：掌握关系运算符基本使用
 * 符号：
 *      == != > < >= <=
 * 注意：
 *      1.关系运算符使用后会得到一个booLean类型结果：成立true，不成立false
 *      2.区分：==  和 = 区别
 *
 */

public class demo6 {

    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b) ;
        System.out.println(a <= b);
        System.out.println(a >= b);
        System.out.println(a != b);
    }
}
